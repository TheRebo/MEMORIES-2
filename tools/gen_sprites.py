"""Regenerate src/data/sprites.ts from every PNG in public/assets/sprites (size + alpha bbox)."""
import glob, os
from PIL import Image
ROOT = os.path.join(os.path.dirname(__file__), '..')
rows = []
for p in sorted(glob.glob(f'{ROOT}/public/assets/sprites/*.png')):
    key = os.path.basename(p)[:-4]
    if key == 'cat_run':
        continue  # spritesheet, loaded separately
    im = Image.open(p).convert('RGBA')
    x0, y0, x1, y1 = im.getbbox() or (0, 0, im.width, im.height)
    rows.append(f"  {key}: {{ file: 'sprites/{key}.png', w: {im.width}, h: {im.height}, bbox: [{x0}, {y0}, {x1 - x0}, {y1 - y0}] }},")
src = open(f'{ROOT}/src/data/sprites.ts').read()
head = src[:src.index('export const SPRITES = {') + len('export const SPRITES = {\n')]
tail = src[src.index('} as const'):]
head = head.replace('// Generated by tools/gen_rooms.py', '// Generated by tools/gen_sprites.py')
open(f'{ROOT}/src/data/sprites.ts', 'w').write(head + '\n'.join(rows) + '\n' + tail)
print(len(rows), 'sprites in manifest')
